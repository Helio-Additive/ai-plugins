import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { compileFromFile } from "json-schema-to-typescript";

const root = resolve(import.meta.dir, "..");

export const schemaTypes = [
  { source: "schemas/agent-plugins/1.0.0/plugin.schema.json", output: "lib/_generated/plugin.ts" },
  { source: "schemas/agent-plugins/1.0.0/mcp.schema.json", output: "lib/_generated/mcp.ts" },
  { source: "schemas/plugin-spec.schema.json", output: "lib/_generated/plugin-spec.ts" },
] as const;

export async function renderSchemaType(source: string): Promise<string> {
  return compileFromFile(resolve(root, source), {
    cwd: root,
    bannerComment: [
      "/*",
      " * Generated by json-schema-to-typescript. Do not edit.",
      ` * Source: ${source}`,
      " * Regenerate: bun run generate:types",
      " */",
    ].join("\n"),
    unknownAny: true,
  });
}

if (import.meta.main) {
  // Compile all schemas before writing so an error cannot leave half-updated types.
  const outputs = await Promise.all(schemaTypes.map(async ({ source, output }) => ({
    output: resolve(root, output), contents: await renderSchemaType(source),
  })));
  for (const { output, contents } of outputs) {
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, contents);
  }
}
